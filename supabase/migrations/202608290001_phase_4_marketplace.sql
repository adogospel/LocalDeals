create function public.resolve_listing_location_and_publication()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  resolved_city text;
  resolved_neighborhood text;
begin
  new.title := trim(new.title);
  new.description := trim(new.description);

  if new.city_id is not null then
    select name into resolved_city
    from public.cities
    where id = new.city_id and is_active;

    if resolved_city is null then
      raise exception 'Selected city is unavailable';
    end if;

    new.city := resolved_city;
    new.custom_city := null;
  else
    new.custom_city := nullif(trim(coalesce(new.custom_city, new.city)), '');
    new.city := new.custom_city;
  end if;

  if new.neighborhood_id is not null then
    select name into resolved_neighborhood
    from public.neighborhoods
    where id = new.neighborhood_id
      and city_id = new.city_id
      and is_active;

    if resolved_neighborhood is null then
      raise exception 'Selected neighborhood is unavailable for this city';
    end if;

    new.neighborhood := resolved_neighborhood;
    new.custom_neighborhood := null;
  else
    new.custom_neighborhood := nullif(trim(coalesce(new.custom_neighborhood, new.neighborhood)), '');
    new.neighborhood := new.custom_neighborhood;
  end if;

  if new.city is null or new.neighborhood is null then
    raise exception 'City and neighborhood are required';
  end if;

  if new.status = 'published' and (
    tg_op = 'INSERT'
    or old.status is distinct from 'published'
  ) then
    if not exists (
      select 1 from public.listing_images where listing_id = new.id
    ) then
      raise exception 'At least one image is required to publish a listing';
    end if;
    new.published_at := timezone('utc', now());
  end if;

  return new;
end;
$$;

