create policy "Public can read active categories"
on public.categories for select to anon, authenticated
using (is_active);

create policy "Public can read published listings"
on public.listings for select to anon, authenticated
using (status in ('published', 'reserved', 'sold'));

create policy "Sellers can read their own listings"
on public.listings for select to authenticated
using ((select auth.uid()) = seller_id);

create policy "Verified profiles can create their own listings"
on public.listings for insert to authenticated
with check (
  (select auth.uid()) = seller_id
  and exists (
    select 1 from public.profiles
    where profiles.id = (select auth.uid())
      and profiles.onboarding_completed
  )
);

create policy "Sellers can update their own listings"
on public.listings for update to authenticated
using ((select auth.uid()) = seller_id)
with check ((select auth.uid()) = seller_id);

create policy "Sellers can delete their own listings"
on public.listings for delete to authenticated
using ((select auth.uid()) = seller_id);

create policy "Public can read images of visible listings"
on public.listing_images for select to anon, authenticated
using (
  exists (
    select 1 from public.listings
    where listings.id = listing_images.listing_id
      and listings.status in ('published', 'reserved', 'sold')
  )
);

