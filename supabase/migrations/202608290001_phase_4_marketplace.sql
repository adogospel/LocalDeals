create type public.listing_condition as enum ('new', 'like_new', 'good', 'fair');
create type public.listing_status as enum ('draft', 'published', 'reserved', 'sold', 'archived');

create table public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  label_fr text not null check (char_length(trim(label_fr)) between 2 and 50),
  label_en text not null check (char_length(trim(label_en)) between 2 and 50),
  symbol text not null check (char_length(trim(symbol)) between 1 and 60),
  sort_order integer not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now())
);

create table public.listings (
  id uuid primary key default gen_random_uuid(),
  seller_id uuid not null references public.profiles (id) on delete cascade,
  category_id bigint not null references public.categories (id) on delete restrict,
  title text not null check (char_length(trim(title)) between 3 and 100),
  description text not null check (char_length(trim(description)) between 20 and 2000),
  price bigint not null check (price between 100 and 1000000000),
  condition public.listing_condition not null,
  status public.listing_status not null default 'draft',
  city_id bigint references public.cities (id) on delete restrict,
  neighborhood_id bigint,
  custom_city text check (custom_city is null or char_length(trim(custom_city)) between 2 and 80),
  custom_neighborhood text check (custom_neighborhood is null or char_length(trim(custom_neighborhood)) between 2 and 100),
  city text not null check (char_length(trim(city)) between 2 and 80),
  neighborhood text not null check (char_length(trim(neighborhood)) between 2 and 100),
  search_vector tsvector generated always as (
    to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(description, ''))
  ) stored,
  published_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint listings_neighborhood_belongs_to_city_fk
    foreign key (neighborhood_id, city_id)
    references public.neighborhoods (id, city_id)
    on delete restrict
);

create table public.listing_images (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings (id) on delete cascade,
  storage_path text not null unique check (char_length(storage_path) between 20 and 500),
  position smallint not null check (position between 0 and 7),
  width integer check (width is null or width between 1 and 20000),
  height integer check (height is null or height between 1 and 20000),
  created_at timestamptz not null default timezone('utc', now()),
  unique (listing_id, position)
);

create table public.favorites (
  user_id uuid not null references public.profiles (id) on delete cascade,
  listing_id uuid not null references public.listings (id) on delete cascade,
  created_at timestamptz not null default timezone('utc', now()),
  primary key (user_id, listing_id)
);

